    private void cargarCombo(JComboBox<ItemCatalogo> combo, List<ItemCatalogo> items, ItemCatalogo marcador) {
        combo.removeAllItems();
        combo.addItem(marcador);
        for (ItemCatalogo item : items) {
            combo.addItem(item);
        }
        combo.setSelectedIndex(0);
    }

    private String codigoSeleccionado(JComboBox<ItemCatalogo> combo) {
        ItemCatalogo item = (ItemCatalogo) combo.getSelectedItem();
        return item == null ? "" : item.getCodigo();
    }

    private LocalDate leerFecha(Date fecha) {
        return fecha == null ? null : fecha.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
    }

    private BigDecimal leerDecimal(String texto, String campo) {
        String limpio = texto.replace("%", "").trim();
        if (limpio.isEmpty()) {
            return null;
        }
        try {
            return new BigDecimal(limpio);
        } catch (NumberFormatException excepcion) {
            throw new IllegalArgumentException(campo + " debe ser un número válido (por ejemplo 20.5).");
        }
    }

    private int leerEntero(String texto) {
        String limpio = texto.trim();
        if (limpio.isEmpty()) {
            return 0;
        }
        try {
            return Integer.parseInt(limpio);
        } catch (NumberFormatException excepcion) {
            throw new IllegalArgumentException("El plazo debe ser un número entero de cuotas.");
        }
    }

    private String dinero(String simbolo, BigDecimal monto) {
        return (simbolo == null ? "" : simbolo + " ") + String.format(Locale.US, "%,.2f", monto);
    }

